-- Wedding site schema and access policies. Rerunnable setup for this site.
create table if not exists public.album_photos (
  id bigint generated by default as identity primary key,
  path text not null unique,
  name text not null check (char_length(name) between 1 and 255),
  created_at timestamptz not null default now()
);
alter table public.album_photos enable row level security;
revoke all on public.album_photos from anon, authenticated;
grant select on public.album_photos to anon, authenticated;
grant insert, delete on public.album_photos to authenticated;
grant usage, select on sequence public.album_photos_id_seq to authenticated;
drop policy if exists "Anyone can view wedding photos" on public.album_photos;
drop policy if exists "Visitors can add wedding photos" on public.album_photos;
drop policy if exists "Public can view wedding photos" on public.album_photos;
drop policy if exists "Admin can view wedding photos" on public.album_photos;
drop policy if exists "Admin can add wedding photos" on public.album_photos;
drop policy if exists "Admin can delete wedding photos" on public.album_photos;
create policy "Public can view wedding photos" on public.album_photos for select to anon using (true);
create policy "Admin can view wedding photos" on public.album_photos for select to authenticated using ((select auth.jwt()->>'email') = 'luan1980tl@gmail.com');
create policy "Admin can add wedding photos" on public.album_photos for insert to authenticated with check ((select auth.jwt()->>'email') = 'luan1980tl@gmail.com');
create policy "Admin can delete wedding photos" on public.album_photos for delete to authenticated using ((select auth.jwt()->>'email') = 'luan1980tl@gmail.com');

create table if not exists public.wedding_wishes (
  id bigint generated by default as identity primary key,
  name text not null check (char_length(name) between 1 and 50),
  age smallint check (age between 1 and 120),
  message text not null check (char_length(message) between 1 and 300),
  created_at timestamptz not null default now()
);
alter table public.wedding_wishes alter column age drop not null;
alter table public.wedding_wishes enable row level security;
revoke all on public.wedding_wishes from anon, authenticated;
grant select, insert on public.wedding_wishes to anon;
grant usage, select on sequence public.wedding_wishes_id_seq to anon;
drop policy if exists "Public can view wedding wishes" on public.wedding_wishes;
drop policy if exists "Visitors can send wedding wishes" on public.wedding_wishes;
create policy "Public can view wedding wishes" on public.wedding_wishes for select to anon using (true);
create policy "Visitors can send wedding wishes" on public.wedding_wishes for insert to anon with check (char_length(name) between 1 and 50 and char_length(message) between 1 and 300);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('wedding-album', 'wedding-album', true, 15728640, array['image/jpeg','image/png','image/webp','image/gif'])
on conflict (id) do update set public=excluded.public, file_size_limit=excluded.file_size_limit, allowed_mime_types=excluded.allowed_mime_types;
drop policy if exists "Public can view wedding album files" on storage.objects;
drop policy if exists "Visitors can upload wedding album files" on storage.objects;
drop policy if exists "Only admin can upload wedding album files" on storage.objects;
drop policy if exists "Only admin can delete wedding album files" on storage.objects;
create policy "Public can view wedding album files" on storage.objects for select to anon, authenticated using (bucket_id='wedding-album');
create policy "Only admin can upload wedding album files" on storage.objects for insert to authenticated with check (bucket_id='wedding-album' and (select auth.jwt()->>'email')='luan1980tl@gmail.com');
create policy "Only admin can delete wedding album files" on storage.objects for delete to authenticated using (bucket_id='wedding-album' and (select auth.jwt()->>'email')='luan1980tl@gmail.com');
